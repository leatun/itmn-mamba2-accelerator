// Main RAM layout (PT_*), Mamba weight bases, Mamba2 constants and H_DEPTH, generated by scripts/m2_layout.py.
// The mixer area [0, PT_MIX_END) is indexed by global group and mirrored to both clusters; the bulk regions
// above it hold T x CH_OUT words (PT_X_IN, PT_INC_OUT, PT_MP3, PT_BOT, ...).
`include "m2_layout.vh"

`define MAIN_ADDR_W       15

// Weight RAM, one per cluster, reloaded by the host per phase: banks P and X of W_MEM_DEPTH words each, bank X at
// weight address + W_MEM_DEPTH for the DMA. A MAC job of w input words per output group puts the PE's words
// [0, wp), wp = ceil(w/2), in bank P (word = base + g*16*wp + k, lane = output row) and the rest in bank X
// transposed (word = base + g*16*(w-wp) + (j-wp)*16 + r, lane = input); w = 1 (encoder) stays in bank P.
// Mamba phase: even output groups in cluster 0's RAM, odd in cluster 1's (compacted); conv taps duplicated.
// Inception phase: work is split by t, so both clusters hold all weights. Bases are multiples of 16.
`define W_MEM_DEPTH       4096
`define W_MEM_ADDR_W      12
`define W_FC_BASE         15'd3584
`define W_P1_BASE         15'd0
`define W_BOT_BASE        15'd256
`define W_B1_BASE         15'd384
`define W_B2_BASE         15'd512
`define W_B3_BASE         15'd800
`define W_B4_BASE         15'd1408
`define W_ENC_BASE        15'd2656

// Const RAM, duplicated per cluster: Mamba2 constants below 64 (m2_layout.vh), Inception/head constants from 64.
`define C_MEM_DEPTH       128
`define C_MEM_ADDR_W      7
`define C_P1_BIAS_BASE    15'd64
`define C_INC_SCALE_BASE  15'd72
`define C_INC_SHIFT_BASE  15'd80
`define C_ENC_BIAS_BASE   15'd88
`define C_FC_BIAS_BASE    15'd92


`define STG_FC            5'd19
// Inception phase
`define STG_P1            5'd10       // k1 conv + fused BN
`define STG_MP3           5'd11       // maxpool k3 s1, edge-clamped
`define STG_B1            5'd12       // k1 conv of MP3
